export interface TranslatableMenuItem {
  id: string;
  name: string;
  price: number;
  category: string;
  section: string;
  description?: string;
  imageIcon?: string;
  imageUrl?: string;
  extras?: { name: string; price: number }[];
  accentColor?: string;
}

export function translateMenuItem(item: TranslatableMenuItem, lang: 'ar' | 'en'): TranslatableMenuItem {
  if (lang === 'ar') return item;
  const trans = ITEMS_TRANSLATIONS[item.id];
  if (!trans) return item;

  const translatedExtras = item.extras?.map(ext => {
    let transName = ext.name;
    if (ext.name.includes('دبل')) transName = 'Add Double Cheese';
    else if (ext.name === 'إضافة بيض') transName = 'Add Egg';
    else if (ext.name.includes('جبن') || ext.name.includes('جبنة')) transName = 'Add Cheese';
    
    return {
      ...ext,
      name: transName
    };
  });

  return {
    ...item,
    name: trans.name || item.name,
    description: trans.description || item.description,
    section: trans.section || item.section,
    extras: translatedExtras
  };
}

